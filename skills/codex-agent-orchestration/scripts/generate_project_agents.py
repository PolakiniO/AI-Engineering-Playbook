def main() -> int:
    parser = argparse.ArgumentParser(description="Generate project-scoped Codex custom agents.")
    parser.add_argument("--project", default=".", help="Target repository root.")
    parser.add_argument("--dry-run", action="store_true", help="Print the generated plan without writing files.")
    parser.add_argument("--force", action="store_true", help="Overwrite existing generated agent files.")
    parser.add_argument(
        "--generic-names",
        action="store_true",
        help="Use role_job names like architect_plan_mapper instead of project-prefixed names.",
    )
    args = parser.parse_args()

    root = Path(args.project).expanduser().resolve()
    if not root.is_dir():
        raise SystemExit(f"project directory does not exist: {root}")

    profile = profile_project(root)
    agents = build_agents(profile, prefixed=not args.generic_names)
    config = config_toml()
    agents_md = agents_markdown(profile, agents)
    plan = {
        "project": str(root),
        "slug": profile.slug,
        "signals": profile.signals,
        "roles": list(agents),
        "files": [".codex/config.toml", *[f".codex/agents/{name}.toml" for name in agents], "AGENTS.md"],
    }

    if args.dry_run:
        print(json.dumps(plan, indent=2))
        return 0

    codex_dir = root / ".codex"
    agent_dir = codex_dir / "agents"
    agent_dir.mkdir(parents=True, exist_ok=True)
    ensure_config(codex_dir / "config.toml", config)
    for file_name, content in agents.items():
        path = agent_dir / f"{file_name}.toml"
        if path.exists() and GENERATED not in path.read_text(encoding="utf-8") and not args.force:
            print(f"skip existing hand-written agent: {path}", file=sys.stderr)
            continue
        path.write_text(content, encoding="utf-8")
        tomllib.loads(content)
    upsert_agents_md(root / "AGENTS.md", agents_md)
    print(json.dumps(plan, indent=2))
    return 0


def profile_project(root: Path) -> ProjectProfile:
    display_name = project_name(root)
    slug = slugify(display_name or root.name)
    signals = set[str]()
    files = {path.name for path in root.iterdir() if path.is_file()}
    all_paths = [path.relative_to(root).as_posix() for path in root.rglob("*") if path.is_file() and skip_path(path, root)]

    package = read_package(root / "package.json")
    dependencies = package.get("dependencies", {})
    dev_dependencies = package.get("devDependencies", {})
    dependency_names = set(dependencies if isinstance(dependencies, dict) else {})
    dependency_names |= set(dev_dependencies if isinstance(dev_dependencies, dict) else {})
    deps = " ".join(sorted(dependency_names)).lower()
    if "package.json" in files or any(path.endswith((".ts", ".tsx", ".js", ".jsx")) for path in all_paths):
        signals.add("javascript")
    if any(token in deps for token in ("react", "next", "vue", "svelte", "vite", "angular")) or any(
        path.endswith((".tsx", ".jsx")) for path in all_paths
    ):
        signals.add("frontend")
    if any(token in deps for token in ("express", "fastify", "nestjs", "koa", "hono")):
        signals.add("backend")
    if "pyproject.toml" in files or "requirements.txt" in files or any(path.endswith(".py") for path in all_paths):
        signals.add("python")
        signals.add("backend")
    if any(part in all_paths for part in ("Dockerfile", "docker-compose.yml")) or any(
        path.startswith((".github/workflows/", "terraform/", "infra/", "k8s/", "helm/")) for path in all_paths
    ):
        signals.add("infra")
    if any(path.startswith(("migrations/", "prisma/", "supabase/", "alembic/")) for path in all_paths):
        signals.add("database")
    if any(path.startswith(("ios/", "android/")) for path in all_paths) or "react-native" in deps or "expo" in deps:
        signals.add("mobile")
    if any(token in deps for token in ("openai", "langchain", "llamaindex", "ai-sdk")) or any(
        token in " ".join(all_paths).lower() for token in ("rag", "llm", "embedding", "agent")
    ):
        signals.add("ai")
    if any(path.endswith((".md", ".mdx", ".rst")) for path in all_paths):
        signals.add("docs")
    if any(token in " ".join(all_paths).lower() for token in ("auth", "permission", "secret", "payment", "stripe", "security")):
        signals.add("security")

    roles = ["architect"]
    if "backend" in signals:
        roles.append("backend")
    if "frontend" in signals:
        roles.append("frontend")
    if "database" in signals:
        roles.append("database")
    if "mobile" in signals:
        roles.append("mobile")
    if "ai" in signals:
        roles.append("ai")
    if not any(role in roles for role in ("backend", "frontend", "database", "mobile", "ai")):
        roles.append("builder")
    if "infra" in signals:
        roles.append("infra")
    roles.append("tester")
    if "security" in signals:
        roles.append("security")
    roles.append("reviewer")
    if len(roles) >= 7:
        roles.append("judge")

    return ProjectProfile(root, slug, display_name, tuple(sorted(signals)), tuple(dict.fromkeys(roles)))


def build_agents(profile: ProjectProfile, *, prefixed: bool) -> dict[str, str]:
    result: dict[str, str] = {}
    for role in profile.roles:
        name = agent_name(profile, role, prefixed=prefixed)
        result[name] = agent_toml(profile, role, name)
    return result


def agent_name(profile: ProjectProfile, role: str, *, prefixed: bool) -> str:
    spec = ROLE_SPECS[role]
    parts = [role, spec.job_slug]
    if prefixed:
        parts.insert(0, profile.slug)
    return "_".join(parts).replace("-", "_")


def agent_toml(profile: ProjectProfile, role: str, name: str) -> str:
    spec = ROLE_SPECS[role]
    instructions = instructions_for(role, profile)
    return f'''{GENERATED}
name = "{name}"
description = "{profile.display_name} {role} agent ({spec.job_title}) for {spec.focus}."
model = "{spec.model}"
model_reasoning_effort = "{spec.effort}"
sandbox_mode = "{spec.sandbox}"

developer_instructions = """
{instructions}
"""
'''



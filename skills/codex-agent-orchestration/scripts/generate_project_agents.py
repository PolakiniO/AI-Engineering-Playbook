def agents_markdown(profile: ProjectProfile, agents: dict[str, str]) -> str:
    names = list(agents)
    architect = find_agent_for_role(names, "architect")
    tester = find_agent_for_role(names, "tester")
    reviewer = find_agent_for_role(names, "reviewer")
    implementers = [
        name for name in names
        if name not in {architect, tester, reviewer}
        and not has_agent_role(name, "security")
        and not has_agent_role(name, "judge")
    ]
    security = next((name for name in names if has_agent_role(name, "security")), None)
    judge = next((name for name in names if has_agent_role(name, "judge")), None)
    lines = [
        START,
        "# Codex Agent Orchestration",
        "",
        f"This project uses a generated Codex subagent team for {profile.display_name}.",
        f"Detected signals: {', '.join(profile.signals) or 'general software project'}.",
        "",
        "Default workflow:",
        "",
        f"1. Spawn `{architect}` first for read-only mapping and sequencing.",
        f"2. Delegate implementation to {', '.join(f'`{name}`' for name in implementers)} when their scopes do not overlap.",
        f"3. Run `{tester}` for validation and coverage gaps.",
    ]
    if security:
        lines.append(f"4. Run `{security}` for security-sensitive boundaries.")
        lines.append(f"5. Run `{reviewer}` for final read-only review.")
    else:
        lines.append(f"4. Run `{reviewer}` for final read-only review.")
    if judge:
        lines.append(f"6. Use `{judge}` to reconcile conflicting subagent results and route fix loops.")
    lines.extend([
        "",
        "The parent session owns requirements, approvals, structured outputs, conflict resolution, and final synthesis.",
        "Avoid concurrent write-capable agents editing the same files.",
        END,
        "",
    ])
    return "\n".join(lines)


def find_agent_for_role(names: list[str], role: str) -> str:
    return next(name for name in names if has_agent_role(name, role))


def has_agent_role(name: str, role: str) -> bool:
    role_job_suffix = f"{role}_{ROLE_SPECS[role].job_slug}"
    return name == role or name == role_job_suffix or name.endswith(f"_{role_job_suffix}")


def ensure_config(path: Path, config: str) -> None:
    if not path.exists():
        path.write_text(config, encoding="utf-8")
        return
    text = path.read_text(encoding="utf-8")
    if "[agents]" not in text:
        path.write_text(text.rstrip() + "\n\n" + config, encoding="utf-8")


def upsert_agents_md(path: Path, section: str) -> None:
    if not path.exists():
        path.write_text(section, encoding="utf-8")
        return
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END) + r"\n?", re.DOTALL)
    if pattern.search(text):
        updated = pattern.sub(section, text)
    else:
        updated = text.rstrip() + "\n\n" + section
    path.write_text(updated, encoding="utf-8")


def config_toml() -> str:
    return """[agents]
enabled = true
max_concurrent_threads_per_session = 8
default_subagent_model = "gpt-5.6-terra"
default_subagent_reasoning_effort = "medium"
"""


def project_name(root: Path) -> str:
    package = read_package(root / "package.json")
    if isinstance(package.get("name"), str) and package["name"].strip():
        return str(package["name"]).split("/")[-1]
    pyproject = root / "pyproject.toml"
    if pyproject.exists():
        try:
            data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
            name = data.get("project", {}).get("name")
            if isinstance(name, str) and name.strip():
                return name
        except tomllib.TOMLDecodeError:
            pass
    return root.name


def read_package(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}
    return data if isinstance(data, dict) else {}


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")
    if not slug:
        return "project"
    if slug[0].isdigit():
        slug = f"project_{slug}"
    return slug[:40]


def skip_path(path: Path, root: Path) -> bool:
    rel = path.relative_to(root).parts
    return not any(part in {".git", ".venv", "node_modules", "dist", "build", "__pycache__"} for part in rel)


if __name__ == "__main__":
    raise SystemExit(main())
